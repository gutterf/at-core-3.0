def match(topic: str):
    """按别名匹配 topic，返回 (key, spec) 或 (None, None)。"""
    t = (topic or "").strip().lower()
    for k, v in SPEC.items():
        if t == k.lower():
            return k, v
        for a in v.get("alias", []):
            if a.lower() in t or t in a.lower():
                return k, v
    return None, None


def render(topic: str, ver="1.0", date="") -> str:
    """把一条 spec 渲染成可直接阅读的正文块。"""
    k, s = match(topic)
    if not s:
        return ""
    out = [f"## {k} · 具体手法层", "", "### 机制", s["mech"], ""]
    if s["steps"]:
        out.append("### 步骤")
        for i, (h, body) in enumerate(s["steps"], 1):
            out.append(f"**{h}**")
            out.append(body)
            out.append("")
    if s["params"]:
        out.append("### 参数表")
        out.append("| 参数 | 取值 | 说明 |")
        out.append("|---|---|---|")
        for a, b, c in s["params"]:
            out.append(f"| {a} | {b} | {c} |")
        out.append("")
    if s["stop"]:
        out.append("### 何时停（最高优先级）")
        for sig, act in s["stop"]:
            out.append(f"- **{sig}** → {act}")
        out.append("")
    if s["fail"]:
        out.append("### 失败态与返工")
        out.append("| 失败态 | 判据 | 返工动作 |")
        out.append("|---|---|---|")
        for a, b, c in s["fail"]:
            out.append(f"| {a} | {b} | {c} |")
        out.append("")
    out.append("### 代价")
    out.append(s["risk"])
    out.append("")
    return "\n".join(out)
